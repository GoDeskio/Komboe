import { mock } from "jest-mock-extended";

import { ForwarderContext } from "../engine";

import { KomboeAliases, KomboeAliasesSettings } from "./komboe-aliases";

describe("Komboe Aliases forwarder", () => {
  const context = mock<ForwarderContext<KomboeAliasesSettings>>();

  afterEach(() => {
    jest.resetAllMocks();
  });

  describe("authenticate", () => {
    it("returns a bearer header with the token", () => {
      context.authenticationToken.mockReturnValue("token");

      const result = KomboeAliases.authenticate(null, context);

      expect(result).toEqual({ Authentication: "token" });
      expect(context.authenticationToken).toHaveBeenCalled();
    });
  });

  describe("settings", () => {
    it("should pass through deserialization", () => {
      const value: any = {};
      const result = KomboeAliases.forwarder.settings.deserializer(value);
      expect(result).toBe(value);
    });
  });

  describe("importBuffer", () => {
    it("should pass through deserialization", () => {
      const value: any = {};
      const result = KomboeAliases.forwarder.importBuffer.options.deserializer(value);
      expect(result).toBe(value);
    });
  });

  describe("createForwardingEmail", () => {
    describe("url", () => {
      it("returns the alias path", () => {
        context.website.mockReturnValue("");
        context.baseUrl.mockReturnValue("");

        const result = KomboeAliases.forwarder.createForwardingEmail.url(null, context);

        expect(result).toEqual("/api/alias/random/new");
      });

      it("includes the website in the alias path", () => {
        context.baseUrl.mockReturnValue("");
        context.website.mockReturnValue("website");

        const result = KomboeAliases.forwarder.createForwardingEmail.url(null, context);

        expect(result).toEqual("/api/alias/random/new?hostname=website");
      });
    });

    describe("body", () => {
      it("returns the alias path", () => {
        context.generatedBy.mockReturnValue("generated by");

        const result = KomboeAliases.forwarder.createForwardingEmail.body(null, context);

        expect(result).toEqual({
          note: "generated by",
        });
      });
    });

    describe("hasJsonPayload", () => {
      it.each([[200], [201]])("returns true when the status is $%i", (status) => {
        const result = KomboeAliases.forwarder.createForwardingEmail.hasJsonPayload(
          { status } as Response,
          context,
        );
        expect(result).toBeTruthy();
      });
    });

    describe("processJson", () => {
      it("should read the email from the response", () => {
        const json = { alias: "foo@example.com" };
        const result = KomboeAliases.forwarder.createForwardingEmail.processJson(json, context);
        expect(result).toEqual(["foo@example.com"]);
      });
    });
  });

  describe("komboe wiring", () => {
    it("requires a self-hosted base URL and an API key", () => {
      expect(KomboeAliases.selfHost).toEqual("always");
      expect(KomboeAliases.baseUrl).toEqual("");
      expect(KomboeAliases.forwarder.settingsConstraints).toEqual({
        token: { required: true },
        baseUrl: { required: true },
      });
    });

    it("uses state keys distinct from SimpleLogin", () => {
      expect(KomboeAliases.forwarder.local.settings.key).toEqual("komboeAliasesForwarder");
      expect(KomboeAliases.forwarder.local.import.key).toEqual("forwarder.KomboeAliases.local.import");
    });

    it("targets the Komboe server alias endpoint", () => {
      context.baseUrl.mockReturnValue("https://vault.example.test");
      context.website.mockReturnValue("shop.example");
      expect(KomboeAliases.forwarder.createForwardingEmail.url(null, context)).toEqual(
        "https://vault.example.test/api/alias/random/new?hostname=shop.example",
      );
    });
  });
});
